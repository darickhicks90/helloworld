"""Generates FoxBox's launcher icon (vector drawables) and Play Store graphics
from one pixel-art design: a nine-tailed kitsune at sunset. Run: python3 play/make_art.py"""
import math, os
from PIL import Image, ImageDraw, ImageFont

C = {'O': '#E8742C', 'o': '#F4A259', 'D': '#3D2414', 'W': '#F7EFDC', 'q': '#22706B', 'r': '#B8521B', 'a': '#8FD9D1', 'A': '#3FB8AF'}
BODY = [".D..........D.", ".DD........DD.", ".DoD......DoD.", ".DOoDDDDDDoOD.", ".DOOOOOOOOOOD.",
        "DOOOOOOOOOOOOD", "DOqDOOOOOOqDOD", "DOOOrOOOOrOOOD", ".DWWWOOOOWWWD.", "..DWWWWWWWWD..",
        "...DWWDDWWD...", "..DOWWWWWWOD..", ".DOOWWWWWWOOD.", ".DOOOWWWWOOOD.", "DOOOOOWWOOOOOD",
        "DOOOOOOOOOOOOD", "DWWDOOOOOODWWD", ".DDDDDDDDDDDD."]
G = 40

def kitsune():
    px = {}
    def disc(cx, cy, r, col, only_empty=False):
        for y in range(int(cy - r - 1), int(cy + r + 2)):
            for x in range(int(cx - r - 1), int(cx + r + 2)):
                if 0 <= x < G and 0 <= y < G and (x + .5 - cx) ** 2 + (y + .5 - cy) ** 2 <= r * r:
                    if not only_empty or (x, y) not in px: px[(x, y)] = col
    bx, by = 20, 31
    tails = []
    steps = 19
    for i in range(9):
        a0 = math.radians(200 + i * (140 / 8))
        curl = (i - 4) * 0.028
        pts = []
        x, y, a = bx, by, a0
        for k in range(steps):
            x += math.cos(a) * 1.1; y += math.sin(a) * 1.1; a += curl
            t = k / (steps - 1)
            if k >= 2: pts.append((x, y, 0.8 + 1.7 * math.sin(math.pi * min(1.0, t * 1.15))))
        tails.append(pts)
    for pts in tails:                      # outlines first
        for x, y, r in pts: disc(x, y, r + 1, 'D')
    for pts in tails:                      # fur, cream tips, fox-fire
        for k, (x, y, r) in enumerate(pts):
            disc(x, y, r, 'W' if k >= len(pts) - 4 else ('o' if k % 6 == 3 else 'O'))
        x, y, _ = pts[-1]
        disc(x + (x - bx) * 0.08, y + (y - by) * 0.08, 1.2, 'a')
    ox, oy = 13, G - len(BODY) - 1
    for j, row in enumerate(BODY):
        for i, ch in enumerate(row):
            if ch != '.': px[(ox + i, oy + j)] = ch
    return px

def sky_bands():
    return ['#4F8E9C', '#79AFA6', '#B9C9A0', '#F3D9B1', '#F6C26B', '#F3A56B', '#E58A5A', '#6FA84A', '#3F7A3A']

def vector(px, path, scale, off):
    by_col = {}
    for (x, y), ch in px.items(): by_col.setdefault(ch, []).append((x, y))
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by play/make_art.py: nine-tailed kitsune -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
    for ch, cells in by_col.items():
        rows = {}
        for x, y in cells: rows.setdefault(y, []).append(x)
        d = []
        for y, xs in rows.items():
            xs.sort(); start = prev = xs[0]
            for x in xs[1:] + [None]:
                if x is not None and x == prev + 1: prev = x; continue
                d.append(f"M{off + start * scale:g},{off + y * scale:g}h{(prev - start + 1) * scale:g}v{scale:g}h-{(prev - start + 1) * scale:g}z")
                if x is not None: start = prev = x
        out.append(f'    <path android:fillColor="{C[ch]}" android:pathData="{"".join(d)}" />')
    out.append('</vector>')
    open(path, 'w').write('\n'.join(out) + '\n')

def background_vector(path):
    bands = sky_bands(); n = len(bands); h = 108 / n
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Sunset over the meadow (generated by play/make_art.py) -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
    for i, c in enumerate(bands):
        out.append(f'    <path android:fillColor="{c}" android:pathData="M0,{i * h:.2f}h108v{h + 0.5:.2f}h-108z" />')
    out.append('    <path android:fillColor="#F6C26B" android:pathData="M30,66a24,24 0,0 1,48 0z" />')
    out.append('</vector>')
    open(path, 'w').write('\n'.join(out) + '\n')

def raster(px, size, scale, off, img=None):
    img = img or Image.new('RGBA', (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    for (x, y), ch in px.items():
        d.rectangle([off + x * scale, off + y * scale, off + (x + 1) * scale - 1, off + (y + 1) * scale - 1], fill=C[ch])
    return img

def sky(w, h, horizon=0.78):
    img = Image.new('RGB', (w, h)); d = ImageDraw.Draw(img)
    bands = sky_bands(); n = len(bands)
    for i, c in enumerate(bands): d.rectangle([0, int(i * h / n), w, int((i + 1) * h / n)], fill=c)
    return img

if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    res = os.path.join(here, '..', 'app', 'src', 'main', 'res', 'drawable')
    px = kitsune()
    vector(px, os.path.join(res, 'ic_launcher_foreground.xml'), 2.0, 14)
    background_vector(os.path.join(res, 'ic_launcher_background.xml'))
    # Play Store icon 512x512
    icon = sky(512, 512); d = ImageDraw.Draw(icon); d.pieslice([142, 205, 370, 433], 180, 360, fill='#F6C26B')
    icon = icon.convert('RGBA'); raster(px, 512, 12, 16, icon)
    icon.convert('RGB').save(os.path.join(here, 'icon-512.png'))
    # Feature graphic 1024x500
    fg = sky(1024, 500).convert('RGBA'); d = ImageDraw.Draw(fg)
    d.pieslice([520, 300, 760, 540], 180, 360, fill='#F6C26B')
    raster(px, 500, 12, 0, fg)
    font_dir = os.path.join(here, '..', 'app', 'src', 'main', 'assets', 'fonts')
    head = ImageFont.truetype(os.path.join(font_dir, 'PressStart2P-Regular.ttf'), 64)
    body = ImageFont.truetype(os.path.join(font_dir, 'PixelifySans.ttf'), 34)
    d.text((514, 158), "FoxBox", font=head, fill='#3D2414'); d.text((508, 152), "FoxBox", font=head, fill='#F7EFDC')
    d.text((510, 250), "write it in the studio", font=body, fill='#3D2414')
    d.text((510, 292), "perform it in the valley", font=body, fill='#3D2414')
    fg.convert('RGB').save(os.path.join(here, 'feature-graphic-1024x500.png'))
    print('ok', len(px), 'pixels')
