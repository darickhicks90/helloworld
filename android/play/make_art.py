"""Generates FoxBox's launcher icon (adaptive vector drawables) and the Play
Store graphics from one design: a modern, clean-line geometric fox head in
orange, aqua and off-white. Run: python3 play/make_art.py"""
import os
from PIL import Image, ImageDraw, ImageFont

ORANGE = '#E8742C'
ORANGE_DARK = '#C95B1F'
ORANGE_LIGHT = '#F4A259'
AQUA = '#3FB8AF'
AQUA_DARK = '#22706B'
CREAM = '#F7EFDC'
INK = '#1F3B3A'

# Shapes in the 108x108 adaptive-icon viewport (safe zone: the middle 66).
def m(points):
    """Mirror a left-half polygon across x = 54."""
    return [(108 - x, y) for x, y in points]

# A flat, symmetrical mark: three shapes and a nose, no shading or eyes.
HEAD = [(28, 25), (45, 39), (63, 39), (80, 25), (83, 56), (54, 85), (25, 56)]
INNER_EAR = [(33, 33), (42, 41), (35, 47)]
MASK = [(25, 56), (44, 58), (54, 70), (64, 58), (83, 56), (54, 85)]
NOSE = [(49.5, 75), (58.5, 75), (54, 80.5)]

SHAPES = [
    (HEAD, ORANGE),
    (INNER_EAR, CREAM), (m(INNER_EAR), CREAM),
    (MASK, CREAM),
    (NOSE, INK),
]


def path_data(points):
    d = f"M{points[0][0]:g},{points[0][1]:g}"
    for x, y in points[1:]:
        d += f"L{x:g},{y:g}"
    return d + "z"


def vector_foreground(path):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by play/make_art.py: clean-line fox -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
    for pts, col in SHAPES:
        out.append(f'    <path android:fillColor="{col}" android:pathData="{path_data(pts)}" />')
    out.append('</vector>')
    open(path, 'w').write('\n'.join(out) + '\n')


def vector_background(path):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Aqua field with a soft ring (generated by play/make_art.py) -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">',
           f'    <path android:fillColor="{AQUA}" android:pathData="M0,0h108v108h-108z" />',
           '</vector>']
    open(path, 'w').write('\n'.join(out) + '\n')


def draw_fox(img, scale, ox, oy):
    d = ImageDraw.Draw(img)
    for pts, col in SHAPES:
        d.polygon([(ox + x * scale, oy + y * scale) for x, y in pts], fill=col)


def supersampled(w, h, paint, k=4):
    big = Image.new('RGB', (w * k, h * k), AQUA)
    paint(big, k)
    return big.resize((w, h), Image.LANCZOS)


if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    res = os.path.join(here, '..', 'app', 'src', 'main', 'res', 'drawable')
    vector_foreground(os.path.join(res, 'ic_launcher_foreground.xml'))
    vector_background(os.path.join(res, 'ic_launcher_background.xml'))

    def icon(img, k):
        d = ImageDraw.Draw(img)
        s = 512 * k / 108
        draw_fox(img, s, 0, 0)
    supersampled(512, 512, icon).save(os.path.join(here, 'icon-512.png'))

    def feature(img, k):
        d = ImageDraw.Draw(img)
        s = 4.2 * k
        draw_fox(img, s, 20 * k, 24 * k)
        font_dir = os.path.join(here, '..', 'app', 'src', 'main', 'assets', 'fonts')
        head = ImageFont.truetype(os.path.join(font_dir, 'PressStart2P-Regular.ttf'), 64 * k)
        body = ImageFont.truetype(os.path.join(font_dir, 'PixelifySans.ttf'), 34 * k)
        d.text((520 * k, 150 * k), "FoxBox", font=head, fill=INK)
        d.text((514 * k, 144 * k), "FoxBox", font=head, fill=CREAM)
        d.text((516 * k, 250 * k), "write it in the studio", font=body, fill=CREAM)
        d.text((516 * k, 292 * k), "perform it in the valley", font=body, fill=CREAM)
    supersampled(1024, 500, feature).save(os.path.join(here, 'feature-graphic-1024x500.png'))
    print('ok')
