"""Generates FoxBox's logo: the launcher icon (adaptive vector drawables) and
the Play Store graphics. The mark is a full-body fox in profile, drawn as a
surreal graphic: it stands on impossibly long, thin legs in front of a pale
moon, and its tail curls up into a spiral. Flat shapes only, in orange, aqua
and off-white. Run: python3 play/make_art.py"""
import math, os
from PIL import Image, ImageDraw, ImageFont

ORANGE = '#E8742C'
ORANGE_DARK = '#B8521B'
CREAM = '#F7EFDC'
AQUA = '#3FB8AF'
AQUA_DEEP = '#22706B'
INK = '#1F3B3A'


def ellipse(cx, cy, rx, ry, n=48, a0=0.0, a1=2 * math.pi):
    return [(cx + rx * math.cos(a0 + (a1 - a0) * i / n), cy + ry * math.sin(a0 + (a1 - a0) * i / n)) for i in range(n + 1)]


def tube(points, w0, w1):
    """A ribbon along a centre line, tapering from width w0 to w1."""
    left, right = [], []
    for i, (x, y) in enumerate(points):
        a = points[max(0, i - 1)]; b = points[min(len(points) - 1, i + 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        d = math.hypot(dx, dy) or 1
        nx, ny = -dy / d, dx / d
        t = i / (len(points) - 1)
        w = (w0 + (w1 - w0) * t) / 2
        left.append((x + nx * w, y + ny * w)); right.append((x - nx * w, y - ny * w))
    return left + right[::-1]


def spiral(cx, cy, r0, r1, a0, a1, n=60):
    return [(cx + (r0 + (r1 - r0) * i / n) * math.cos(a0 + (a1 - a0) * i / n),
             cy + (r0 + (r1 - r0) * i / n) * math.sin(a0 + (a1 - a0) * i / n)) for i in range(n + 1)]


def leg(x0, y0, x1, y1, w):
    return [(x0 - w / 2, y0), (x0 + w / 2, y0), (x1 + w * 0.35, y1), (x1 - w * 0.35, y1)]


# ---- the mark, in the 108×108 adaptive-icon viewport (safe zone 18..90)
MOON = ellipse(54, 45, 29, 29, 72)
# tail: sweeps back from the rump, then curls into a spiral
tail_line = [(42, 46), (35, 48.5), (28, 47.5)] + spiral(26, 35.5, 12, 3.0, math.pi / 2, math.pi / 2 + 2 * math.pi * 1.1, 80)[1:]
TAIL = tube(tail_line, 13, 3.2)
TAIL_TIP = tube(tail_line[-24:], 5.0, 3.2)
BODY = ellipse(51, 45, 15, 8.5, 48)
HEAD = [(56, 40), (60, 32), (63.5, 24), (64.5, 11), (70, 21.5), (74, 24), (84, 29.5), (82.8, 32.2), (74.5, 35.5), (69, 45), (62, 47)]
EAR_IN = [(65.4, 16.5), (68.4, 22.8), (65.0, 24.2)]
CHEST = [(69, 45), (74.5, 35.5), (82.8, 32.2), (78, 36.5), (71.5, 46), (64.5, 51)]
EYE = ellipse(71.6, 27.8, 1.9, 1.1, 20)
NOSE = [(82.6, 28.8), (85.2, 30.0), (83.2, 31.6)]
LEGS_BACK = [leg(41, 50, 39, 87, 2.4), leg(57, 51, 58, 87, 2.4)]
LEGS_FRONT = [leg(45, 51, 44.5, 88, 2.6), leg(62, 50, 64, 88, 2.6)]
FEET = [ellipse(x, 88.4, 1.8, 0.9, 12) for x in (39, 58)] + [ellipse(x, 89, 1.9, 1.0, 12) for x in (44.5, 64)]
STARS = [ellipse(x, y, r, r, 8) for x, y, r in ((30, 22, 0.9), (82, 58, 0.7), (76, 16, 0.6))]

SHAPES = [
    (MOON, CREAM),
    *[(s, CREAM) for s in STARS],
    *[(l, ORANGE_DARK) for l in LEGS_BACK],
    (TAIL, ORANGE), (TAIL_TIP, CREAM),
    (BODY, ORANGE),
    *[(l, ORANGE) for l in LEGS_FRONT],
    *[(f, INK) for f in FEET],
    (HEAD, ORANGE), (EAR_IN, CREAM), (CHEST, CREAM),
    (EYE, AQUA_DEEP), (NOSE, INK),
]


def path_data(pts):
    return "M" + "L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "z"


def vector_foreground(path):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by play/make_art.py: a full-body fox in profile on stilt legs before the moon -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
    for pts, col in SHAPES:
        out.append(f'    <path android:fillColor="{col}" android:pathData="{path_data(pts)}" />')
    out.append('</vector>')
    open(path, 'w').write('\n'.join(out) + '\n')


def vector_background(path):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Flat aqua (generated by play/make_art.py) -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">',
           f'    <path android:fillColor="{AQUA}" android:pathData="M0,0h108v108h-108z" />',
           '</vector>']
    open(path, 'w').write('\n'.join(out) + '\n')


def draw_mark(img, scale, ox, oy):
    d = ImageDraw.Draw(img)
    for pts, col in SHAPES:
        d.polygon([(ox + x * scale, oy + y * scale) for x, y in pts], fill=col)


def supersampled(w, h, paint, k=4):
    big = Image.new('RGB', (w * k, h * k), AQUA)
    paint(big, k)
    return big.resize((w, h), Image.LANCZOS)


def kotlin_mark(path):
    """The same shapes for drawing the logo inside the app (project screen)."""
    cols = {ORANGE: 'Pal.ORANGE', ORANGE_DARK: 'Pal.ORANGE_D', CREAM: 'Pal.CREAM', AQUA_DEEP: 'Pal.AQUA_D', INK: '0xFF1F3B3A.toInt()'}
    lines = ['package app.foxbox.ui', '', 'import android.graphics.Canvas', 'import android.graphics.Paint', 'import android.graphics.Path', '',
             '/** The FoxBox logo mark (generated by play/make_art.py): a fox on stilt legs before the moon, in a 108-unit box. */',
             'object LogoMark {', '    private val SHAPES: List<Pair<Int, FloatArray>> = listOf(']
    for pts, col in SHAPES:
        nums = ', '.join(f'{v:.1f}f' for xy in pts for v in xy)
        lines.append(f'        {cols[col]} to floatArrayOf({nums}),')
    lines += ['    )', '    private val paint = Paint(Paint.ANTI_ALIAS_FLAG)', '    private val path = Path()', '',
              '    /** Draw the mark with its 108-unit box at (x, y), `size` pixels across. */',
              '    fun draw(c: Canvas, x: Float, y: Float, size: Float) {',
              '        val k = size / 108f',
              '        for ((col, p) in SHAPES) {',
              '            path.reset(); path.moveTo(x + p[0] * k, y + p[1] * k)',
              '            var i = 2',
              '            while (i < p.size) { path.lineTo(x + p[i] * k, y + p[i + 1] * k); i += 2 }',
              '            path.close(); paint.color = col; c.drawPath(path, paint)',
              '        }', '    }', '}', '']
    open(path, 'w').write('\n'.join(lines))


if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    res = os.path.join(here, '..', 'app', 'src', 'main', 'res', 'drawable')
    kotlin_mark(os.path.join(here, '..', 'app', 'src', 'main', 'java', 'app', 'foxbox', 'ui', 'LogoMark.kt'))
